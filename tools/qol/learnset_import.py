def generate(profile):
    if (profile['engine_revision'] != REVISION or profile['target_generation'] != 9
            or profile['champions_changes']):
        raise ValueError('expected the approved pinned Gen IX profile')
    species = profile['species']
    if {s['species'] for s in species} != set(range(1, 494)):
        raise ValueError('expected exactly the original 493 base species')
    # Resolve only the approved IDs; never infer IDs from newer official numbers.
    for move_id, constant in SUPPORTED.items():
        move = next(m for m in profile['moves'] if m['engine_id'] == move_id)
        # The source abbreviates this full name to fit its legacy string limit.
        expected_constant = ('MOVE_PRECIPICEBLADES' if move_id == 622 else constant)
        if 'MOVE_' + move['caps_name'].replace('-', '_').replace(' ', '_') != expected_constant:
            raise ValueError(f'move ID {move_id} has changed')
    ids = {name: move_id for move_id, name in SUPPORTED.items()}
    rows = sorted({(s['species'], entry['Level'], ids[entry['Move']])
                   for s in species
                   for entry in profile['learnsets'][s['constant']]['LevelMoves']
                   if entry['Move'] in ids})
    if any(not 0 <= level <= 100 for _, level, _ in rows):
        raise ValueError('level outside native range')
    if max(Counter(s for s, _, _ in rows).values(), default=0) > 5:
        raise ValueError('increase and audit QOL_LEVEL_UP_ADDITIONS_MAX before import')
    lines = ['// Generated by tools/qol/learnset_import.py; do not edit.',
             f'// hg-engine {REVISION}; Gen IX, base forms 1..493.',
             '// Original learnsets remain intact. Only implemented new move IDs are added.',
             '// Level 0 is an evolution move, offered by the evolution-specific reader.']
    lines.extend(f'QOL_LEVEL_UP_MOVE({s}, {level}, {move})' for s, level, move in rows)
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', type=Path,
                        default=ROOT / '.local-tools/validation/gen9-import-profile.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'include/data/qol_learnsets.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads(args.profile.read_text()))
    if args.check:
        if not args.output.exists() or args.output.read_text() != output:
            raise SystemExit('generated learnset overlay is stale')
    else:
        args.output.write_text(output)


if __name__ == '__main__':
    main()
